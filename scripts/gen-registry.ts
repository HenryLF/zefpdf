// Writes app/plugins/registry.generated.ts: one static import per
// plugins/<id>/index.tsx. The browser bundle is built ahead of time, so the
// plugin list has to be known at build time; config.json's `plugins.enabled`
// then decides at runtime which of them are switched on.
//
// The file is only rewritten when its content changes, so `bun build --watch`
// is not retriggered by every run.

import { join, relative } from "node:path";

const ROOT = join(import.meta.dir, "..");
const OUT = join(ROOT, "app/plugins/registry.generated.ts");
const ID = /^[a-z0-9-]+$/;

const ids = [...new Bun.Glob("plugins/*/index.tsx").scanSync({ cwd: ROOT })]
  .map((p) => p.split("/")[1]!)
  .filter((id) => {
    if (ID.test(id)) return true;
    console.warn(`gen-registry: skipping plugins/${id} (id must match ${ID})`);
    return false;
  })
  .sort();

const ident = (id: string) => `p_${id.replace(/-/g, "_")}`;
const from = (id: string) =>
  relative(join(ROOT, "app/plugins"), join(ROOT, "plugins", id, "index.tsx"));

const content = `// Generated by scripts/gen-registry.ts — do not edit, do not commit.
import type { Plugin } from "./types";
${ids.map((id) => `import ${ident(id)} from "${from(id)}";`).join("\n")}

export const ALL_PLUGINS: Plugin[] = [${ids.map(ident).join(", ")}];
`;

const file = Bun.file(OUT);
if (!(await file.exists()) || (await file.text()) !== content) {
  await Bun.write(OUT, content);
  console.log(`gen-registry: ${ids.length} plugin(s): ${ids.join(", ") || "none"}`);
}
